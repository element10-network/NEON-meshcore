#!/bin/sh
# Builds Neon's MeshCore radio firmware for the Heltec V3: MeshCore at the pinned commit
# (MESHCORE_COMMIT), Neon's hooks (neon/companion_radio.patch) and code (neon/*.cpp, *.h).
# The result is unsigned: sign.sh signs it on hq with the project's firmware key.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
commit=$(cat "$here/MESHCORE_COMMIT")
work="$here/build/MeshCore"
if [ ! -d "$work/.git" ]; then
    mkdir -p "$here/build"
    git init -q "$work"
    git -C "$work" remote add origin https://github.com/meshcore-dev/MeshCore.git
fi
git -C "$work" fetch -q --depth 1 origin "$commit"
git -C "$work" checkout -q -f "$commit"
git -C "$work" clean -qfd -e .pio
git -C "$work" apply "$here/neon/companion_radio.patch"
mkdir -p "$work/src/helpers/neon"
cp "$here"/neon/*.cpp "$here"/neon/*.h "$work/src/helpers/neon/"
# The firmware keys secure boot may trust (SHA-256 digests, espsecure.py digest_sbv2_public_key):
# exactly two 64-hex lines, the project's key then its offline backup. The firmware revokes any
# other digest slot, so sign.sh checks its keys against this same file (a mismatch would revoke every
# slot: a dead board).
digests="$here/neon/key-digests.hex"
[ -f "$digests" ] || { echo "no $digests: the firmware keys' digests are needed (README, 'The firmware keys (hq)')" >&2; exit 1; }
lines=$(grep -v '^#' "$digests" | grep -c . || true)
[ "$lines" -eq 2 ] || { echo "key-digests.hex: exactly two digests (project key, backup key)" >&2; exit 1; }
d1=$(grep -v '^#' "$digests" | grep . | sed -n 1p); d2=$(grep -v '^#' "$digests" | grep . | sed -n 2p)
for d in "$d1" "$d2"; do
    printf '%s' "$d" | grep -Eqx '[0-9a-f]{64}' || { echo "bad digest line: $d" >&2; exit 1; }
done
[ "$d1" != "$d2" ] || { echo "key-digests.hex: the two digests are the same" >&2; exit 1; }
{
    echo "// Generated by build.sh from neon/key-digests.hex."
    printf '#define NEON_KEY_DIGESTS {'
    for d in "$d1" "$d2"; do printf '{'; printf '%s' "$d" | sed 's/\(..\)/0x\1,/g'; printf '},'; done
    echo '}'
} > "$work/src/helpers/neon/KeyDigest.h"
cp "$here/platformio.local.ini" "$work/platformio.local.ini"
export PLATFORMIO_SETTING_ENABLE_TELEMETRY=No
(cd "$work" && pio run -e neon_heltec_v3)
# The bootloader with secure boot (bootloader/), unsigned too, from sdkconfig.defaults every time
# (a kept sdkconfig would silently keep old settings), and checked: a wrong bootloader locks boards.
rm -f "$here/bootloader/sdkconfig.bootloader"
(cd "$here/bootloader" && pio run)
for opt in CONFIG_SECURE_BOOT=y CONFIG_SECURE_BOOT_V2_ENABLED=y CONFIG_SECURE_BOOT_V2_RSA_ENABLED=y \
    CONFIG_SECURE_ENABLE_SECURE_ROM_DL_MODE=y CONFIG_SECURE_BOOT_V2_ALLOW_EFUSE_RD_DIS=y; do
    grep -qx "$opt" "$here/bootloader/sdkconfig.bootloader" || { echo "bootloader built without $opt" >&2; exit 1; }
done
for opt in CONFIG_PARTITION_TABLE_OFFSET=0x8000 CONFIG_ESPTOOLPY_FLASHSIZE_8MB=y; do
    grep -qx "$opt" "$here/bootloader/sdkconfig.bootloader" || { echo "bootloader built without $opt" >&2; exit 1; }
done
for opt in CONFIG_SECURE_BOOT_INSECURE CONFIG_SECURE_BOOT_ENABLE_AGGRESSIVE_KEY_REVOKE CONFIG_SECURE_BOOT_ALLOW_JTAG \
    CONFIG_EFUSE_VIRTUAL CONFIG_SECURE_FLASH_ENC_ENABLED; do
    ! grep -qx "$opt=y" "$here/bootloader/sdkconfig.bootloader" || { echo "bootloader built with $opt" >&2; exit 1; }
done
mkdir -p "$here/out"
b="$work/.pio/build/neon_heltec_v3"
cp "$b/firmware.bin" "$here/out/firmware.bin"
cp "$b/partitions.bin" "$here/out/partitions.bin"
cp "${PLATFORMIO_CORE_DIR:-$HOME/.platformio}/packages/framework-arduinoespressif32/tools/partitions/boot_app0.bin" "$here/out/boot_app0.bin"
cp "$here/bootloader/.pio/build/bootloader/bootloader.bin" "$here/out/bootloader.bin"
printf '%s\n%s\n' "$d1" "$d2" > "$here/out/key-digests.hex"
(cd "$here/out" && sha256sum bootloader.bin partitions.bin boot_app0.bin firmware.bin key-digests.hex > UNSIGNED.SHA256SUMS)
# A signed bootloader must end before the partition table (0x8000) with its 4 KiB signature.
size=$(wc -c < "$here/out/bootloader.bin")
[ $(( (size + 4095) / 4096 * 4096 + 4096 )) -le 32768 ] || { echo "bootloader too large to sign: $size bytes" >&2; exit 1; }
echo "built (unsigned) in out/: bootloader.bin partitions.bin boot_app0.bin firmware.bin key-digests.hex UNSIGNED.SHA256SUMS"
